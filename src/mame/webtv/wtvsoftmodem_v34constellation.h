	constexpr void rot90(int32_t &re, int32_t &im, int32_t quadrant)
	{
		int32_t r = re;
		int32_t i = im;

		switch (quadrant & 3)
		{
			case 0:
				re = r;
				im = i;
				break;

			case 1:
				re = i;
				im = -r;
				break;

			case 2:
				re = -r;
				im = -i;
				break;

			case 3:
				re = -i;
				im = r;
				break;
		}
	}

